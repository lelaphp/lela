//! `zend_try_compile_special_func` (design §6.1): the names php's
//! compiler serves itself instead of emitting the call, in the order
//! `zend_try_compile_special_func_ex` tries them, and what each becomes
//! here. php gives such a call one of two shapes: a constant where the
//! arguments are constant, and an opcode of its own otherwise. This
//! compiler serves the constant for the four names whose constant needs
//! no opcode, `strlen`, `chr`, `ord` and `defined`, and the opcode for
//! the rows whose kernel the engine has: `ZEND_STRLEN`, `ZEND_TYPE_CHECK`
//! with its type mask, `ZEND_DEFINED` with its cache slot, `ZEND_COUNT`
//! with `sizeof`'s bit and `ZEND_IN_ARRAY` with its table, and the call
//! `call_user_func` and `call_user_func_array` are made without a frame
//! of their own, `INIT_USER_CALL` with `SEND_USER` or `SEND_ARRAY`
//! (`crate::emit::user_call`). Every other row is
//! [`Special::Opcode`] and is compiled as the ordinary `INIT_FCALL`,
//! `SEND_*` and `DO_ICALL`, never folded to something else, so the value
//! is php's where the op array is not yet; a row moves off
//! `Special::Opcode` when its kernel lands, and the table's order never
//! moves. Which names the corpus reaches is `data/special-funcs.md`,
//! regenerated by `scripts/special-funcs-census.sh` from this table.
//!
//! php reads three gates before the table. The function table, which
//! must hold the name as one of php's own natives
//! (`fbc->type == ZEND_INTERNAL_FUNCTION`, at
//! `zend_try_compile_special_func`) so a disabled and redeclared name
//! keeps its user body, is read here as
//! [`Emit::native`] over the natives the engine handed the compiler; a
//! name the bundle has not is the call. Two are not read, because this
//! compiler has nothing to read them from: the compiler option that
//! turns the table off (`ZEND_COMPILE_NO_BUILTINS`), and unpacked or
//! named arguments (`zend_args_contain_unpack_or_named`), which the
//! reader does not read. `chr` and `ord` fold only in a call read for
//! its value (`type == BP_VAR_R`), which every call here is.

use php_heap::{Key, Zval, ZvalType, numeric_prefix};
use php_unit::Opcode;

use crate::CompileError;
use crate::emit::{CastTo, Emit, Where, truth};
use php_syntax::tree;

/// What php's compiler makes of one name in the table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Special {
    /// `zend_compile_func_strlen`: the length of a constant string,
    /// `ZEND_STRLEN` over anything else.
    Strlen,
    /// `zend_compile_func_typecheck` and `zend_compile_func_is_scalar`:
    /// `ZEND_TYPE_CHECK` over the argument, the types it answers `true`
    /// for as php's `MAY_BE_*` bits in `extended_value`.
    TypeCheck(u32),
    /// `zend_compile_func_chr`: the one-byte string of a long written as
    /// such, 0 to 255; the call otherwise.
    Chr,
    /// `zend_compile_func_ord`: the byte of a one-byte string written as
    /// such; the call otherwise.
    Ord,
    /// `zend_compile_func_defined`: `true` for a name the compiler
    /// substitutes, `ZEND_DEFINED` over another name with a cache slot
    /// in `extended_value`, the call for a name with a namespace or a
    /// class in it.
    Defined,
    /// `zend_compile_func_count`: `ZEND_COUNT` over the argument, with
    /// `extended_value` set where the name written was `sizeof`, so the
    /// `TypeError` names the function as written.
    Count { sizeof: bool },
    /// `zend_compile_func_in_array`: `ZEND_IN_ARRAY` over the needle and
    /// a table built from a haystack of constants, with `$strict`, read
    /// off a constant third argument by `zend_is_true`, in
    /// `extended_value`; the call otherwise.
    InArray,
    /// `zend_compile_func_cufa`: the callback's `INIT_USER_CALL`, or the
    /// `INIT_FCALL` of the function a written name holds, and the array
    /// sent by `SEND_ARRAY`, where the call has exactly two arguments.
    CallUserFuncArray,
    /// `zend_compile_func_cuf`: the callback initialised as
    /// [`Special::CallUserFuncArray`]'s is, and each argument after it
    /// sent by `SEND_USER`, where the call has one argument or more.
    CallUserFunc,
    /// `zend_compile_func_clone`: `ZEND_CLONE` over the one argument,
    /// which is what `clone $o` and `clone($o)` both are; two arguments
    /// or none is the call to php 8.5's `clone()` function.
    Clone,
    /// `zend_compile_func_sprintf`: a constant format under 256 bytes of
    /// `%s`, `%d` and `%%` alone, with one argument for each placeholder,
    /// is a rope of its pieces, a `%d` cast to `int` first; anything else
    /// is the call.
    Sprintf,
    /// A shape that is an opcode of its own (`ZEND_BOOL`, `ZEND_CAST`,
    /// `ZEND_GET_CLASS`,
    /// `ZEND_GET_CALLED_CLASS`, `ZEND_GET_TYPE`, `ZEND_FUNC_NUM_ARGS`,
    /// `ZEND_FUNC_GET_ARGS`, `ZEND_ARRAY_KEY_EXISTS`) and has no kernel
    /// here yet: the ordinary call.
    Opcode,
}

/// The `MAY_BE_*` bit for one of php's types, `1 << IS_*`, which is how
/// `zend_compile_func_typecheck` writes `extended_value`.
const fn may_be(ty: ZvalType) -> u32 {
    1 << (ty as u32)
}

/// `MAY_BE_BOOL`: `(1 << IS_FALSE) | (1 << IS_TRUE)`, what
/// `zend_compile_func_typecheck` writes for `_IS_BOOL`.
const MAY_BE_BOOL: u32 = may_be(ZvalType::False) | may_be(ZvalType::True);

/// What `zend_compile_func_is_scalar` writes: a bool, a long, a double
/// or a string.
const MAY_BE_SCALAR: u32 =
    MAY_BE_BOOL | may_be(ZvalType::Long) | may_be(ZvalType::Double) | may_be(ZvalType::String);

/// `zend_try_compile_special_func_ex`'s names, in its order, each with
/// what this compiler makes of it. A row php reaches through two names
/// (`is_int` and `is_integer`, `count` and `sizeof`) is two rows here,
/// in the order the names stand in php's condition.
pub(crate) const TABLE: &[(&[u8], Special)] = &[
    (b"strlen", Special::Strlen),
    (b"is_null", Special::TypeCheck(may_be(ZvalType::Null))),
    (b"is_bool", Special::TypeCheck(MAY_BE_BOOL)),
    (b"is_long", Special::TypeCheck(may_be(ZvalType::Long))),
    (b"is_int", Special::TypeCheck(may_be(ZvalType::Long))),
    (b"is_integer", Special::TypeCheck(may_be(ZvalType::Long))),
    (b"is_float", Special::TypeCheck(may_be(ZvalType::Double))),
    (b"is_double", Special::TypeCheck(may_be(ZvalType::Double))),
    (b"is_string", Special::TypeCheck(may_be(ZvalType::String))),
    (b"is_array", Special::TypeCheck(may_be(ZvalType::Array))),
    (b"is_object", Special::TypeCheck(may_be(ZvalType::Object))),
    (
        b"is_resource",
        Special::TypeCheck(may_be(ZvalType::Resource)),
    ),
    (b"is_scalar", Special::TypeCheck(MAY_BE_SCALAR)),
    (b"boolval", Special::Opcode),
    (b"intval", Special::Opcode),
    (b"floatval", Special::Opcode),
    (b"doubleval", Special::Opcode),
    (b"strval", Special::Opcode),
    (b"defined", Special::Defined),
    (b"chr", Special::Chr),
    (b"ord", Special::Ord),
    (b"call_user_func_array", Special::CallUserFuncArray),
    (b"call_user_func", Special::CallUserFunc),
    (b"in_array", Special::InArray),
    (b"count", Special::Count { sizeof: false }),
    (b"sizeof", Special::Count { sizeof: true }),
    (b"get_class", Special::Opcode),
    (b"get_called_class", Special::Opcode),
    (b"gettype", Special::Opcode),
    (b"func_num_args", Special::Opcode),
    (b"func_get_args", Special::Opcode),
    (b"array_slice", Special::Opcode),
    (b"array_key_exists", Special::Opcode),
    (b"sprintf", Special::Sprintf),
    (b"clone", Special::Clone),
];

/// The row for a lowered, unqualified name, as
/// `zend_try_compile_special_func_ex` finds it: the first whose name
/// matches, and none for a name the table has not.
pub(crate) fn row(lowered: &[u8]) -> Option<Special> {
    TABLE
        .iter()
        .find(|(name, _)| *name == lowered)
        .map(|(_, shape)| *shape)
}

impl Emit<'_> {
    /// `zend_try_ct_eval_const` for a name with no namespace in it: php's
    /// special constants, `true`, `false` and `null` in any case
    /// (`zend_get_special_const`), then the persistent table.
    fn ct_eval_const(&mut self, name: &[u8]) -> Result<Option<Zval>, CompileError> {
        Ok(match name.to_ascii_lowercase().as_slice() {
            b"true" => Some(Zval::bool(true)),
            b"false" => Some(Zval::bool(false)),
            b"null" => Some(Zval::null()),
            _ => self.persistent(name)?,
        })
    }

    /// `zend_try_compile_special_func`: where the value is once the call
    /// is served, a constant or the temporary of the opcode emitted for
    /// it, and nothing where the name is not one of the engine's
    /// natives, is not in the table or has a row with no kernel yet,
    /// which is the ordinary call.
    ///
    /// ```php
    /// var_dump(1 + strlen('a'), strlen('a' . 'b'), chr(65), ord('a'), defined('INF'), defined('true'));
    /// ```
    /// ```expect
    /// int(2)
    /// int(2)
    /// string(1) "A"
    /// int(97)
    /// bool(true)
    /// bool(true)
    /// ```
    pub(crate) fn special(
        &mut self,
        lowered: &[u8],
        arguments: &[tree::Expr],
    ) -> Result<Option<Where>, CompileError> {
        if !self.native(lowered) {
            return Ok(None);
        }
        match row(lowered) {
            Some(Special::Strlen) => self.strlen(arguments),
            Some(Special::TypeCheck(mask)) => self.over_one(Opcode::TypeCheck, arguments, mask),
            Some(Special::Chr) => Ok(self.chr(arguments)?.map(Where::Constant)),
            Some(Special::Ord) => Ok(self.ord(arguments)?.map(Where::Constant)),
            Some(Special::Defined) => self.defined(arguments),
            Some(Special::Count { sizeof }) => {
                self.over_one(Opcode::Count, arguments, u32::from(sizeof))
            }
            Some(Special::Clone) => self.over_one(Opcode::Clone, arguments, 0),
            Some(Special::InArray) => self.in_array(arguments),
            Some(Special::CallUserFuncArray) => self.call_user_func_array(arguments),
            Some(Special::CallUserFunc) => self.call_user_func(arguments),
            Some(Special::Sprintf) => self.sprintf(arguments),
            Some(Special::Opcode) | None => Ok(None),
        }
    }

    /// The constant shape alone, for a call standing where a constant
    /// expression is folded: what [`Self::special`] would leave as a
    /// constant, and nothing where it would emit an opcode, which is
    /// what leaves that opcode to be emitted where the call stands.
    /// Emits nothing, so a fold tried and refused costs no opline.
    pub(crate) fn special_constant(
        &mut self,
        lowered: &[u8],
        arguments: &[tree::Expr],
    ) -> Result<Option<Zval>, CompileError> {
        if !self.native(lowered) {
            return Ok(None);
        }
        match row(lowered) {
            Some(Special::Strlen) => self.strlen_constant(arguments),
            Some(Special::Chr) => self.chr(arguments),
            Some(Special::Ord) => self.ord(arguments),
            Some(Special::Defined) => self.defined_constant(arguments),
            Some(
                Special::TypeCheck(_)
                | Special::Count { .. }
                | Special::Clone
                | Special::InArray
                | Special::CallUserFuncArray
                | Special::CallUserFunc
                | Special::Sprintf
                | Special::Opcode,
            )
            | None => Ok(None),
        }
    }

    /// `zend_compile_func_strlen`: one argument, compiled, and a constant
    /// string is its length; `ZEND_STRLEN` over anything else, a
    /// constant that is not a string included (`strlen(1)`).
    fn strlen(&mut self, arguments: &[tree::Expr]) -> Result<Option<Where>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let value = self.expr(*argument)?;
        if let Where::Constant(constant) = value
            && let Some(s) = constant.as_str()
        {
            return Ok(Some(Where::Constant(length(s.len()))));
        }
        Ok(Some(self.emit_unary(Opcode::Strlen, value, 0)))
    }

    /// `zend_compile_func_sprintf` (`Z/Zend/zend_compile.c:4859`): the
    /// format folded (`zend_eval_const_expr`) to a string under 256
    /// bytes whose every `%` opens `%s`, `%d` or `%%`, with as many
    /// arguments after it as it has placeholders; else the call, so an
    /// argument count that does not match is sprintf's own
    /// `ArgumentCountError`. The empty format is the empty string. The
    /// arguments are compiled first, as a call's would be, and then each
    /// piece is one element of a rope in order: the text between
    /// placeholders a constant, the first `%` of a `%%` kept in it; a
    /// `%s` the argument, a constant converted to its string here and an
    /// array cast as the request serves it; a `%d` the argument cast to `int` just
    /// before its element. So a value that will not convert is raised
    /// where the call stands, with no frame of sprintf's.
    ///
    /// ```php
    /// $n = "7"; var_dump(sprintf("%s-%d-100%%", "a", $n), sprintf(""), sprintf("%s", 1.5));
    /// try { sprintf("%s/%s", "x", new stdClass); } catch (Error $e) { echo $e->getMessage(), " at ", count($e->getTrace()), "\n"; }
    /// try { sprintf("%s/%s", "x"); } catch (ArgumentCountError $e) { echo $e->getMessage(), " at ", count($e->getTrace()), "\n"; }
    /// ```
    /// ```expect
    /// string(8) "a-7-100%"
    /// string(0) ""
    /// string(3) "1.5"
    /// Object of class stdClass could not be converted to string at 0
    /// 3 arguments are required, 2 given at 1
    /// ```
    fn sprintf(&mut self, arguments: &[tree::Expr]) -> Result<Option<Where>, CompileError> {
        let Some((format, values)) = arguments.split_first() else {
            return Ok(None);
        };
        let Some(format) = self.eval_const(*format)? else {
            return Ok(None);
        };
        let Some(format) = format.as_str().map(|s| s.bytes().to_vec()) else {
            return Ok(None);
        };
        if format.len() >= 256 {
            return Ok(None);
        }
        let Some(pieces) = sprintf_pieces(&format) else {
            return Ok(None);
        };
        let placeholders = pieces
            .iter()
            .filter(|piece| !matches!(piece, Piece::Text(..)))
            .count();
        if placeholders != values.len() {
            return Ok(None);
        }
        if format.is_empty() {
            return Ok(Some(Where::Constant(self.string(b"")?)));
        }
        let mut compiled = Vec::with_capacity(values.len());
        for value in values {
            compiled.push(self.expr(*value)?);
        }
        // The counts matched above, so every placeholder has its value.
        let mut compiled = compiled.into_iter();
        let (mut count, mut init_at) = (0u32, 0usize);
        for piece in pieces {
            let element = match piece {
                Piece::Text(from, to) => Where::Constant(self.string(&format[from..to])?),
                Piece::Str | Piece::Long => {
                    let Some(value) = compiled.next() else {
                        break;
                    };
                    match (piece, value) {
                        (Piece::Long, value) => self.emit_cast(value, CastTo::Long),
                        (_, Where::Constant(constant)) => match self.stringified(constant)? {
                            Some(text) => Where::Constant(text),
                            None => self.emit_cast(Where::Constant(constant), CastTo::Str),
                        },
                        (_, value) => value,
                    }
                }
            };
            let at = self.rope_add(count, element);
            if count == 0 {
                init_at = at;
            }
            count += 1;
        }
        Ok(Some(self.rope_finalize(count, init_at)))
    }

    /// [`Self::strlen`]'s constant arm alone: the length of a constant
    /// string, and nothing for anything else.
    fn strlen_constant(&mut self, arguments: &[tree::Expr]) -> Result<Option<Zval>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let Some(value) = self.constant_of(*argument)? else {
            return Ok(None);
        };
        Ok(value.as_str().map(|s| length(s.len())))
    }

    /// `zend_compile_func_typecheck`, `zend_compile_func_is_scalar`,
    /// `zend_compile_func_count` and `zend_compile_func_clone`: one
    /// argument, compiled, and the opcode
    /// over it into a temporary with `extended_value` as given; two
    /// arguments or none is the call, whatever the arguments are.
    fn over_one(
        &mut self,
        opcode: Opcode,
        arguments: &[tree::Expr],
        extended_value: u32,
    ) -> Result<Option<Where>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let value = self.expr(*argument)?;
        Ok(Some(self.emit_unary(opcode, value, extended_value)))
    }

    /// `zend_compile_func_in_array` (`Z/Zend/zend_compile.c:4419`): two
    /// arguments, or three whose third is a value written as such or a
    /// constant the compiler substitutes, read by `zend_is_true` and so
    /// never type-checked; and a haystack that is an array expression of
    /// constants. The table is built from the haystack's values, each a
    /// key holding `true`: under `$strict` a string by
    /// `zend_hash_add` and a long by `zend_hash_index_add`, anything
    /// else refusing; without it a string that is not numeric, anything
    /// else refusing, since a hash lookup could not compare it as `==`
    /// does. The empty haystack is the empty table either way. Then the
    /// needle, compiled, and `ZEND_IN_ARRAY` over it and the table into a
    /// temporary, `$strict` in `extended_value`. Every refusal is the
    /// ordinary call, which refuses a third argument that is no bool
    /// under `strict_types` as any native parameter is refused, and
    /// raises nothing of the haystack's fold, since the call folds it
    /// again where php reads the node it folded in place.
    ///
    /// ```php
    /// declare(strict_types=1);
    /// class S { function __toString(): string { return "s"; } }
    /// var_dump(in_array(1, [1], 1), in_array(1, [], 1), in_array(1, [], null), in_array('1', [1, 'x'], true), in_array(1, ['1', 'x'], TRUE), in_array('a', ['a', 'b'], null), in_array(1, [1], PHP_INT_SIZE), in_array(1, [], \null));
    /// var_dump(in_array('b', ['a', 'b']), in_array(0, ['a']), in_array(true, ['a']), in_array(null, ['', 'a']), in_array(new S, ['s']), in_array(1.0, ['a']));
    /// $f = 'in_array';
    /// try { $f(1, [1], 1); } catch (TypeError $e) { echo $e->getMessage(), "\n"; }
    /// try { in_array(1, [1], null); } catch (TypeError $e) { echo $e->getMessage(), "\n"; }
    /// try { in_array('a', ['a', '1'], null); } catch (TypeError $e) { echo $e->getMessage(), "\n"; }
    /// try { in_array('a', ['a', 'b'], $s ?? null); } catch (TypeError $e) { echo $e->getMessage(), "\n"; }
    /// var_dump(in_array('1', ['a', '1']), in_array($u, ['', 'a']));
    /// var_dump(in_array(1, [NAN . '', 1]));
    /// ```
    /// ```expect
    /// Warning: unexpected NAN value was coerced to string in %s on line 12
    /// bool(true)
    /// bool(false)
    /// bool(false)
    /// bool(false)
    /// bool(false)
    /// bool(true)
    /// bool(true)
    /// bool(false)
    /// bool(true)
    /// bool(false)
    /// bool(true)
    /// bool(true)
    /// bool(true)
    /// bool(false)
    /// in_array(): Argument #3 ($strict) must be of type bool, int given
    /// in_array(): Argument #3 ($strict) must be of type bool, null given
    /// in_array(): Argument #3 ($strict) must be of type bool, null given
    /// in_array(): Argument #3 ($strict) must be of type bool, null given
    ///
    /// Warning: Undefined variable $u in %s on line 11
    /// bool(true)
    /// bool(true)
    /// bool(true)
    /// ```
    fn in_array(&mut self, arguments: &[tree::Expr]) -> Result<Option<Where>, CompileError> {
        let (needle, haystack, strict) = match arguments {
            [needle, haystack] => (*needle, *haystack, false),
            [needle, haystack, flag] => match self.in_array_flag(*flag)? {
                Some(strict) => (*needle, *haystack, strict),
                None => return Ok(None),
            },
            _ => return Ok(None),
        };
        let raised = self.raised();
        let Some(keys) = self
            .array_entries(haystack)?
            .and_then(|entries| in_array_keys(&entries, strict))
        else {
            self.unraise(raised);
            return Ok(None);
        };
        let table = self.lay_array(&keys)?;
        let needle = self.expr(needle)?;
        Ok(Some(self.emit_binary(
            Opcode::InArray,
            needle,
            Where::Constant(table),
            u32::from(strict),
        )))
    }

    /// The `$strict` `zend_compile_func_in_array` reads off a third
    /// argument: `zend_is_true` over a value written as such
    /// (`ZEND_AST_ZVAL`) or over a constant `zend_try_ct_eval_const`
    /// substitutes (`ZEND_AST_CONST`), and nothing for any other
    /// argument, a constant left to the program among them.
    fn in_array_flag(&mut self, flag: tree::Expr) -> Result<Option<bool>, CompileError> {
        if let tree::Expr::NameRef(token) = self.peel(flag) {
            return Ok(self.named_constant(token)?.map(truth));
        }
        Ok(self.written(flag)?.map(truth))
    }

    /// `zend_compile_func_chr`: the one-byte string for a long written
    /// as such, 0 to 255 (`ZVAL_CHAR`). A long written any other way
    /// (`chr(1 + 64)`, `chr(-0)`), one outside the byte and anything
    /// else is the call, as php leaves it.
    fn chr(&mut self, arguments: &[tree::Expr]) -> Result<Option<Zval>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let Some(byte) = self
            .written(*argument)?
            .and_then(Zval::as_long)
            .and_then(|n| u8::try_from(n).ok())
        else {
            return Ok(None);
        };
        Ok(Some(self.string(&[byte])?))
    }

    /// `zend_compile_func_ord`: the byte of a one-byte string written as
    /// such; a longer or an empty string, or anything else, is the call.
    fn ord(&mut self, arguments: &[tree::Expr]) -> Result<Option<Zval>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let Some(value) = self.written(*argument)? else {
            return Ok(None);
        };
        Ok(value.as_str().and_then(|s| match s.bytes() {
            [byte] => Some(Zval::long(i64::from(*byte))),
            _ => None,
        }))
    }

    /// `zend_compile_func_defined`: one argument written as a value, read
    /// as a string (`zval_get_string`). A name with a `\` or a `:` in it
    /// is the call; a name the compiler substitutes where it is written
    /// ([`Emit::ct_eval_const`]) is `true`; and the rest is
    /// `ZEND_DEFINED` over the name as a constant string, with a cache
    /// slot in `extended_value`.
    fn defined(&mut self, arguments: &[tree::Expr]) -> Result<Option<Where>, CompileError> {
        let Some(name) = self.defined_name(arguments)? else {
            return Ok(None);
        };
        let Some(bytes) = name.as_str() else {
            return Ok(None);
        };
        if self.ct_eval_const(bytes.bytes())?.is_some() {
            return Ok(Some(Where::Constant(Zval::bool(true))));
        }
        let slot = self.cache_slot();
        Ok(Some(self.emit_unary(
            Opcode::Defined,
            Where::Constant(name),
            slot,
        )))
    }

    /// [`Self::defined`]'s constant arm alone: `true` for a name the
    /// compiler substitutes, and nothing for a name it would leave to
    /// the opcode or the call.
    fn defined_constant(&mut self, arguments: &[tree::Expr]) -> Result<Option<Zval>, CompileError> {
        let Some(name) = self.defined_name(arguments)? else {
            return Ok(None);
        };
        let Some(bytes) = name.as_str() else {
            return Ok(None);
        };
        Ok(self.ct_eval_const(bytes.bytes())?.map(|_| Zval::bool(true)))
    }

    /// The name `zend_compile_func_defined` reads: the one argument
    /// written as a value, as a string, and nothing where the argument
    /// is anything else, there are two or none, or the name has a `\`
    /// or a `:` in it.
    fn defined_name(&mut self, arguments: &[tree::Expr]) -> Result<Option<Zval>, CompileError> {
        let [argument] = arguments else {
            return Ok(None);
        };
        let Some(value) = self.written(*argument)? else {
            return Ok(None);
        };
        let Some(name) = self.stringified(value)? else {
            return Ok(None);
        };
        let Some(bytes) = name.as_str() else {
            return Ok(None);
        };
        let bytes = bytes.bytes();
        if bytes.contains(&b'\\') || bytes.contains(&b':') {
            return Ok(None);
        }
        Ok(Some(name))
    }

    /// Whether an argument stands in php's tree as a value,
    /// `ZEND_AST_ZVAL`, and which: a number or a string as written, or a
    /// `.` over two of them, which php's parser folds before the compiler
    /// sees it (`zend_ast_create_concat_op`). `true`, `false`, `null` and
    /// a named constant are `ZEND_AST_CONST` and are not; nor is any
    /// other expression, whether the compiler would fold it or not, which
    /// is why `chr(1 + 64)` is a call where `ord('a' . '')` is a
    /// constant.
    pub(crate) fn written(&mut self, expr: tree::Expr) -> Result<Option<Zval>, CompileError> {
        match self.peel(expr) {
            tree::Expr::LiteralExpr(_)
            | tree::Expr::NowdocExpr(_)
            | tree::Expr::InterpolatedStringExpr(_)
            | tree::Expr::HeredocExpr(_) => {
                if !self.is_written_value(expr) {
                    return Ok(None);
                }
                Ok(Some(self.constant_expr(expr)?))
            }
            tree::Expr::BinaryExpr(id) => {
                let (lhs, op, rhs) = self.binary_of(id);
                if op != Some(php_syntax::SyntaxKind::DOT) {
                    return Ok(None);
                }
                let Some(rhs) = rhs else {
                    return Ok(None);
                };
                let (Some(a), Some(b)) = (self.written(lhs)?, self.written(rhs)?) else {
                    return Ok(None);
                };
                self.concat_fold(a, b)
            }
            _ => Ok(None),
        }
    }
}

/// The table `zend_compile_func_in_array` builds from a haystack's
/// values: each value a key holding `true`, the first of equal keys
/// kept (`zend_hash_add`), a string as its bytes and never the integer
/// a decimal one would be under `zend_symtable_update`. Under
/// `$strict` a string or a long is a key; without it a string that is not
/// numeric (`is_numeric_string` with no errors allowed) is. Any other
/// value is nothing, which is the ordinary call.
fn in_array_keys(entries: &[(Key, Zval)], strict: bool) -> Option<Vec<(Key, Zval)>> {
    let mut keys: Vec<(Key, Zval)> = Vec::with_capacity(entries.len());
    for (_, value) in entries {
        let key = match (value.kind(), value.as_str()) {
            (ZvalType::String, Some(s)) if strict || !is_numeric(s.bytes()) => Key::Str(s),
            (ZvalType::Long, _) if strict => Key::Long(value.as_long()?),
            _ => return None,
        };
        if !keys.iter().any(|(held, _)| *held == key) {
            keys.push((key, Zval::bool(true)));
        }
    }
    Some(keys)
}

/// `is_numeric_string` with `allow_errors` off: the whole string is one
/// number, whitespace around it allowed.
fn is_numeric(bytes: &[u8]) -> bool {
    numeric_prefix(bytes).is_some_and(|(_, trailing)| !trailing)
}

/// `ZVAL_LONG(&result->u.constant, Z_STRLEN(...))`: a length as the long
/// it is written as.
fn length(len: usize) -> Zval {
    Zval::long(i64::try_from(len).unwrap_or(i64::MAX))
}

/// One piece of a format `zend_compile_func_sprintf` takes: text between
/// placeholders, as a range of the format, or a placeholder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Piece {
    Text(usize, usize),
    Str,
    Long,
}

/// `zend_compile_func_sprintf`'s two walks over the format: none where a
/// `%` ends it or opens anything but `s`, `d` or `%`; else the pieces in
/// order, a `%%`'s first `%` kept in the text before it and its second
/// dropped, and no empty text.
fn sprintf_pieces(format: &[u8]) -> Option<Vec<Piece>> {
    let mut pieces = Vec::new();
    let (mut p, mut offset) = (0usize, 0usize);
    while let Some(found) = format[p..].iter().position(|&b| b == b'%') {
        let at = p + found;
        let q = at + 1;
        let placeholder = match format.get(q)? {
            b's' => Some(Piece::Str),
            b'd' => Some(Piece::Long),
            b'%' => None,
            _ => return None,
        };
        let text_end = if placeholder.is_none() { q } else { at };
        if text_end != offset {
            pieces.push(Piece::Text(offset, text_end));
        }
        if let Some(placeholder) = placeholder {
            pieces.push(placeholder);
        }
        p = q + 1;
        offset = p;
    }
    if offset != format.len() {
        pieces.push(Piece::Text(offset, format.len()));
    }
    Some(pieces)
}
