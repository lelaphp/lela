//! The files the manifest's `generated` predicate names, rendered from the
//! rule each is derived from (harness-design.md §4.1, §13 D.19). Today that
//! is `ext/clippy.toml` from `ext.no-locks`: the `disallowed-types` list
//! with the rule's text as each reason, wildcards expanded from
//! `Cargo.lock`. The committed copy is held to the rendering by `budget`.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use crate::lock::{CargoLock, package_of};
use crate::manifest::{Manifest, Rule};

/// Every generated file the manifest names, with its rendering.
pub fn render_all(root: &Path, manifest: &Manifest) -> Result<BTreeMap<String, String>> {
    let mut out = BTreeMap::new();
    for rule in &manifest.rules {
        for (file, from) in rule.predicate.generated.iter().flatten() {
            out.insert(file.clone(), render(root, manifest, file, from)?);
        }
    }
    Ok(out)
}

/// Write every generated file under the root; the paths written.
pub fn write_all(root: &Path, manifest: &Manifest) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();
    for (file, text) in render_all(root, manifest)? {
        let path = root.join(&file);
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
        written.push(path);
    }
    Ok(written)
}

/// Render one generated file from the rule it is derived from.
pub fn render(root: &Path, manifest: &Manifest, file: &str, from: &str) -> Result<String> {
    let rule = manifest.rule(from).with_context(|| {
        format!("{file} is generated from rule {from}, which the manifest lacks")
    })?;
    match file.rsplit_once('/').map_or(file, |(_, name)| name) {
        "clippy.toml" => clippy_toml(root, rule, file),
        _ => bail!("no generator renders {file} (from rule {from})"),
    }
}

/// `clippy.toml` with `disallowed-types` from a `deny_types` rule.
fn clippy_toml(root: &Path, rule: &Rule, file: &str) -> Result<String> {
    let types = rule.predicate.deny_types.as_ref().with_context(|| {
        format!(
            "{file} renders disallowed-types, but rule {} has no deny_types",
            rule.id
        )
    })?;
    let lock = CargoLock::load(root)?;
    let cited = rule.adr.adr_cited();
    let reason = if cited.is_empty() {
        rule.text.clone()
    } else {
        format!("{} {cited}", rule.text)
    };
    let mut out = format!(
        "# Generated by `xtask generate` from seams.toml rule {} {}; do not edit.\n\
         # A copy that differs from the regenerated one fails `xtask budget` under\n\
         # generated.committed. Clippy finds this file by nearest-file search, so it\n\
         # covers every ext/<name> and nothing under crates/.\n\
         disallowed-types = [\n",
        rule.id,
        if cited.is_empty() {
            "(no ADR)"
        } else {
            cited.as_str()
        }
    );
    for ty in types {
        let expanded = match ty.strip_suffix("::*") {
            Some(prefix) => {
                let paths = lock.expand(prefix)?;
                if paths.is_empty() {
                    let _ = writeln!(
                        out,
                        "    # {ty}: {} is not a Cargo.lock package at this revision; nothing to deny",
                        package_of(prefix)
                    );
                }
                paths
            }
            None => vec![ty.clone()],
        };
        for path in expanded {
            let _ = writeln!(
                out,
                "    {{ path = {}, reason = {} }},",
                toml_string(&path),
                toml_string(&reason)
            );
        }
    }
    out.push_str("]\n");
    Ok(out)
}

fn toml_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
