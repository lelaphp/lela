//! libmbfl, compiled from the sources vendored at `libmbfl/` (design
//! §7.2, revision 47): `php-src/ext/mbstring/libmbfl` at the tag
//! `oracle.toml` pins, byte for byte, under its `LICENSE`, the LGPL-2.1.
//! The file list is the one php's `config.m4` compiles, read off the copy
//! beside this file; the include path is php's, `libmbfl` and
//! `libmbfl/mbfl`, behind `shim/`, which holds the Zend names php 8's
//! libmbfl includes, and `shim/shim.c`, which gives the binding a symbol
//! for each `static inline` function of `mb_convert_buf` it calls. Nothing
//! is discovered on the system for libmbfl.
//!
//! Oniguruma is the platform's, as the oracle links it for `mb_ereg*`:
//! found through `pkg-config oniguruma` and linked, never vendored.
//!
//! The tables `mbstring.c` and `php_unicode.c` read are generated here
//! from the headers php generated them into, so they stay one copy:
//! `unicode_data.h` and `rare_cp_bitvec.h` (vendored beside this file
//! from `php-src/ext/mbstring`), `libmbfl/mbfl/eaw_table.h`,
//! `libmbfl/filters/unicode_prop.h`, and the numbering of libmbfl's
//! encodings and languages with the flags its headers define.

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    compile_libmbfl();
    link_oniguruma();
    let out = std::env::var("OUT_DIR").unwrap_or_default();
    let tables = generate_tables();
    if let Err(error) = std::fs::write(Path::new(&out).join("tables.rs"), tables) {
        println!("cargo:warning=tables.rs: {error}");
    }
    for path in [
        "libmbfl",
        "shim",
        "config.m4",
        "unicode_data.h",
        "rare_cp_bitvec.h",
        "build.rs",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
}

fn compile_libmbfl() {
    let m4 = std::fs::read_to_string("config.m4").unwrap_or_default();
    let mut build = cc::Build::new();
    // php compiles C and C++ with -DNDEBUG unless it is built with
    // --enable-debug or --enable-debug-assertions (Z/configure.ac:840), the
    // two builds that set ZEND_DEBUG, as debug assertions are this build's:
    // assert() is live exactly where Rust's debug_assertions is.
    if std::env::var_os("CARGO_CFG_DEBUG_ASSERTIONS").is_none() {
        build.define("NDEBUG", None);
    }
    build
        .include("shim")
        .include("libmbfl")
        .include("libmbfl/mbfl")
        .opt_level(2)
        .warnings(false)
        .file("shim/shim.c");
    let mut sources = 0;
    for word in m4.split_whitespace() {
        if word.starts_with("libmbfl/") && Path::new(word).extension().is_some_and(|e| e == "c") {
            build.file(word);
            sources += 1;
        }
    }
    if sources == 0 {
        println!("cargo:warning=config.m4 names no libmbfl source");
    }
    build.compile("mbfl");
}

/// `MB_ONIGURUMA_VERSION` is the linked library's version, which
/// `pkg-config` states for the build.
fn link_oniguruma() {
    match pkg_config::Config::new()
        .atleast_version("6.8")
        .probe("oniguruma")
    {
        Ok(library) => println!("cargo:rustc-env=ONIG_VERSION={}", library.version),
        Err(error) => {
            println!("cargo:warning=pkg-config oniguruma: {error}");
            println!("cargo:rustc-link-lib=onig");
            println!("cargo:rustc-env=ONIG_VERSION=");
        }
    }
}

/// `tables.rs`: each table a `static` of its C name upper-cased without
/// its leading underscores, each size and `#define` a `const`, and the
/// two enums' members as `ENCODING_*` and `LANGUAGE_*`.
fn generate_tables() -> String {
    let mut out = String::from("// Generated by build.rs from php-src's headers; see there.\n");
    for header in [
        "unicode_data.h",
        "rare_cp_bitvec.h",
        "libmbfl/mbfl/eaw_table.h",
        "libmbfl/filters/unicode_prop.h",
    ] {
        arrays(&read(header), &mut out);
    }
    let mut seen = Vec::new();
    for header in [
        "libmbfl/mbfl/mbfl_consts.h",
        "libmbfl/mbfl/mbfilter.h",
        "libmbfl/mbfl/mbfl_encoding.h",
        "libmbfl/mbfl/eaw_table.h",
        "libmbfl/filters/translit_kana_jisx0201_jisx0208.h",
    ] {
        defines(&read(header), &mut out, &mut seen);
    }
    members(
        &read("libmbfl/mbfl/mbfl_encoding.h"),
        "mbfl_no_encoding",
        &mut out,
    );
    members(
        &read("libmbfl/mbfl/mbfl_language.h"),
        "mbfl_no_language",
        &mut out,
    );
    out
}

fn read(path: &str) -> String {
    strip_comments(&std::fs::read_to_string(path).unwrap_or_default())
}

fn strip_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("/*") {
        out.push_str(&rest[..start]);
        rest = rest[start + 2..]
            .find("*/")
            .map_or("", |end| &rest[start + 2 + end + 2..]);
    }
    out.push_str(rest);
    out
}

fn rust_name(c_name: &str) -> String {
    c_name.trim_start_matches('_').to_uppercase()
}

fn rust_type(c_type: &str) -> &'static str {
    match c_type
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .as_str()
    {
        "short" => "i16",
        "unsigned short" => "u16",
        "unsigned char" => "u8",
        _ => "u32",
    }
}

fn number(token: &str) -> Option<i64> {
    let token = token.trim().trim_start_matches('(').trim_end_matches(')');
    let (negative, digits) = token
        .strip_prefix('-')
        .map_or((false, token), |d| (true, d));
    let digits = digits.trim_end_matches(['u', 'U', 'l', 'L']);
    let value = match digits
        .strip_prefix("0x")
        .or_else(|| digits.strip_prefix("0X"))
    {
        Some(hex) => i64::from_str_radix(hex, 16).ok()?,
        None => digits.parse().ok()?,
    };
    Some(if negative { -value } else { value })
}

/// `static const T name[] = { ... };` and `static const T name = n;`.
fn arrays(text: &str, out: &mut String) {
    let mut rest = text;
    while let Some(at) = rest.find("static const ") {
        rest = &rest[at + "static const ".len()..];
        // An anonymous struct's members end in `;` before the table does.
        let is_struct = rest.starts_with("struct");
        if is_struct {
            rest = rest.find('}').map_or("", |close| &rest[close + 1..]);
        }
        let Some(end) = rest.find(';') else { break };
        let statement = &rest[..end];
        rest = &rest[end + 1..];
        let Some((head, body)) = statement.split_once('=') else {
            continue;
        };
        let head = head.trim();
        if let Some(open) = head.find('[') {
            let before = head[..open].trim();
            let (c_type, name) = before
                .rsplit_once(char::is_whitespace)
                .unwrap_or(("", before));
            let element = if is_struct { "u32" } else { rust_type(c_type) };
            let values: Vec<i64> = body
                .split(|c: char| c == ',' || c == '{' || c == '}' || c.is_whitespace())
                .filter_map(number)
                .collect();
            let listed: Vec<String> = values.iter().map(i64::to_string).collect();
            writeln!(
                out,
                "#[allow(dead_code)]\npub(crate) static {}: [{element}; {}] = [{}];",
                rust_name(name),
                values.len(),
                listed.join(", ")
            )
            .ok();
        } else if let (Some((c_type, name)), Some(value)) =
            (head.rsplit_once(char::is_whitespace), number(body))
        {
            writeln!(
                out,
                "#[allow(dead_code)]\npub(crate) const {}: {} = {value};",
                rust_name(name),
                rust_type(c_type)
            )
            .ok();
        }
    }
}

/// `#define NAME n`, a number alone.
fn defines(text: &str, out: &mut String, seen: &mut Vec<String>) {
    for line in text.lines() {
        let mut words = line.split_whitespace();
        if words.next() != Some("#define") {
            continue;
        }
        let (Some(name), Some(value), None) = (words.next(), words.next(), words.next()) else {
            continue;
        };
        if let Some(value) = number(value)
            && !seen.iter().any(|s| s == name)
        {
            seen.push(name.to_owned());
            let value = u32::try_from(value & 0xFFFF_FFFF).unwrap_or(0);
            writeln!(
                out,
                "#[allow(dead_code)]\npub(crate) const {name}: u32 = {value:#x};"
            )
            .ok();
        }
    }
}

/// `enum name { a = -1, b, c, ... };` as `i32` constants.
fn members(text: &str, name: &str, out: &mut String) {
    let Some(start) = text.find(&format!("enum {name} {{")) else {
        return;
    };
    let body = &text[start..];
    let body = &body[body.find('{').unwrap_or(0) + 1..body.find('}').unwrap_or(0)];
    let prefix = format!("{name}_");
    let mut next = 0i64;
    for member in body.split(',') {
        let member = member.trim();
        if member.is_empty() {
            continue;
        }
        let (ident, value) = match member.split_once('=') {
            Some((ident, value)) => (ident.trim(), number(value).unwrap_or(next)),
            None => (member, next),
        };
        next = value + 1;
        let short = ident.strip_prefix(&prefix).unwrap_or(ident).to_uppercase();
        let kind = if name.ends_with("encoding") {
            "ENCODING"
        } else {
            "LANGUAGE"
        };
        writeln!(
            out,
            "#[allow(dead_code)]\npub(crate) const {kind}_{short}: i32 = {value};"
        )
        .ok();
    }
}
